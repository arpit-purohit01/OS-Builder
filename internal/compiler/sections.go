// ------------------------------------------------------------------ health

func (c *ctx) health() {
	var session []string
	switch c.s.Foundation.Profile {
	case "desktop-gnome", "desktop-kde":
		session = []string{"display-manager.service"}
	case "kiosk-cage", "thin-client":
		session = []string{"foundry-kiosk.service"}
	}
	var critical []string
	if *c.s.Security.AutoUpdates || c.s.Ecosystem.Fleet.Enroll {
		critical = append(critical, "foundry-agent.service")
	}
	c.t.add(extra+"usr/lib/foundry/health", 0o755, embedded("health/health"))
	c.t.add(extra+"usr/lib/foundry/health.conf", 0o644, fmt.Sprintf("SESSION_UNITS=%q\nCRITICAL_UNITS=%q\n", strings.Join(session, " "), strings.Join(critical, " ")))
	c.t.add(extra+"usr/lib/systemd/system/foundry-health.service", 0o644, `[Unit]
Description=Foundry boot health check
Documentation=https://docs.foundry.dev/updates#health
Before=boot-complete.target
After=graphical.target multi-user.target
FailureAction=reboot
# Live/installer sessions are not update trials.
ConditionKernelCommandLine=!foundry.installer=1

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/lib/foundry/health

[Install]
RequiredBy=boot-complete.target
`)
	c.enable("foundry-health.service", "systemd-boot-check-no-failures.service")
	// Boot-test reporter: inert unless the hypervisor passes the
	// foundry.boottest credential (SMBIOS type 11), which only the platform's
	// test harness does. Same image for tests and customers.
	c.t.add(extra+"usr/lib/foundry/boottest-report", 0o755, embedded("health/boottest-report"))
	c.t.add(extra+"usr/lib/systemd/system/foundry-boottest.service", 0o644, `[Unit]
Description=Foundry boot test report (test harness only)
ConditionCredential=foundry.boottest
# No After= on foundry-health/boot-complete: they are ordered after
# multi-user.target, which this unit is wanted by (ordering cycle). The script
# waits for the boot transaction instead (systemctl is-system-running --wait).

[Service]
Type=exec
ExecStart=/usr/lib/foundry/boottest-report
TimeoutStartSec=300

[Install]
WantedBy=multi-user.target
`)
	c.enable("foundry-boottest.service")
}

// ----------------------------------------------------------------- helpers

func uniq(xs []string) []string {
	var out []string
	for i, x := range xs {
		if i == 0 || x != xs[i-1] {
			out = append(out, x)
		}
	}
	return out
}

func uniqOrdered(xs []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, x := range xs {
		if !seen[x] {
			seen[x] = true
			out = append(out, x)
		}
	}
	return out
}

func mustJSON(v any) string {
	b, err := jsonMarshalIndent(v)
	if err != nil {
		panic(err)
	}
	return string(b) + "\n"
}

func hexToRGB(h string) (int, int, int) {
	h = strings.TrimPrefix(h, "#")
	r, _ := strconv.ParseUint(h[0:2], 16, 8)
	g, _ := strconv.ParseUint(h[2:4], 16, 8)
	b, _ := strconv.ParseUint(h[4:6], 16, 8)
	return int(r), int(g), int(b)
}
