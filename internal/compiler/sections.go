var levelCmdline = map[string][]string{
	"relaxed":  {"randomize_kstack_offset=on", "vsyscall=none"},
	"balanced": {"lockdown=integrity", "init_on_alloc=1", "slab_nomerge", "page_alloc.shuffle=1", "randomize_kstack_offset=on", "vsyscall=none", "debugfs=off", "module.sig_enforce=1"},
	"hardened": {"lockdown=confidentiality", "init_on_alloc=1", "init_on_free=1", "slab_nomerge", "page_alloc.shuffle=1", "randomize_kstack_offset=on", "vsyscall=none", "debugfs=off", "module.sig_enforce=1", "iommu=force"},
}

func (c *ctx) security() {
	sec, acc := c.s.Security, c.s.Access
	c.cmdline = append(c.cmdline, levelCmdline[sec.Level]...)

	sys := map[string]string{
		"kernel.kptr_restrict":               "2",
		"kernel.dmesg_restrict":              "1",
		"kernel.unprivileged_bpf_disabled":   "1",
		"net.core.bpf_jit_harden":            "2",
		"kernel.yama.ptrace_scope":           "1",
		"kernel.kexec_load_disabled":         "1",
		"kernel.sysrq":                       "0",
		"kernel.perf_event_paranoid":         "3",
		"dev.tty.ldisc_autoload":             "0",
		"fs.protected_symlinks":              "1",
		"fs.protected_hardlinks":             "1",
		"fs.protected_fifos":                 "2",
		"fs.protected_regular":               "2",
		"fs.suid_dumpable":                   "0",
		"vm.unprivileged_userfaultfd":        "0",
		"net.ipv4.conf.all.rp_filter":        "2",
		"net.ipv4.conf.all.accept_redirects": "0",
		"net.ipv6.conf.all.accept_redirects": "0",
		"net.ipv4.conf.all.send_redirects":   "0",
		"net.ipv4.tcp_syncookies":            "1",
	}
	if sec.Level == "hardened" {
		sys["kernel.yama.ptrace_scope"] = "2"
		sys["net.ipv4.conf.all.rp_filter"] = "1"
	}
	if sec.Level == "relaxed" {
		delete(sys, "kernel.kexec_load_disabled")
	}
	if acc.RootModel == "developer" {
		sys["kernel.sysrq"] = "176"
		sys["kernel.perf_event_paranoid"] = "2"
	}
	if c.s.Kernel.Flavor == "gaming" {
		sys["vm.max_map_count"] = "1048576"
	}
	c.sysctl("60-foundry-security.conf", sys)

	// Firewall (nftables). Default policy from spec; allow-list services.
	ports := map[string][]string{
		"mdns":       {"udp dport 5353"},
		"ssh":        {"tcp dport 22"},
		"kdeconnect": {"tcp dport 1714-1764", "udp dport 1714-1764"},
		"printing":   {"tcp dport 631", "udp dport 631"},
		"rdp":        {"tcp dport 3389"},
		"vnc":        {"tcp dport 5900"},
	}
	var allow []string
	if sec.Firewall != nil {
		for _, a := range sec.Firewall.Allow {
			allow = append(allow, ports[a]...)
		}
	}
	if c.s.Ecosystem.Handoff.Enabled {
		allow = append(allow, ports["kdeconnect"]...)
	}
	sort.Strings(allow)
	allow = uniq(allow)
	policy := "drop"
	if sec.Firewall != nil && sec.Firewall.Default == "allow-all" {
		policy = "accept"
	}
	var nf strings.Builder
	nf.WriteString("#!/usr/sbin/nft -f\n# Generated by Foundry\nflush ruleset\n\ntable inet foundry {\n  chain input {\n")
	fmt.Fprintf(&nf, "    type filter hook input priority filter; policy %s;\n", policy)
	nf.WriteString("    ct state established,related accept\n    ct state invalid drop\n    iifname \"lo\" accept\n")
	nf.WriteString("    ip protocol icmp icmp type { echo-request, destination-unreachable, time-exceeded } limit rate 10/second accept\n")
	nf.WriteString("    ip6 nexthdr icmpv6 accept\n    udp dport 68 accept\n    udp dport 546 accept\n")
	for _, a := range allow {
		fmt.Fprintf(&nf, "    %s accept\n", a)
	}
	nf.WriteString("  }\n  chain forward {\n    type filter hook forward priority filter; policy drop;\n  }\n}\n")
	c.t.add(extra+"etc/nftables.conf", 0o755, nf.String())
	c.enable("nftables.service")

	switch sec.USBStorage {
	case "read-only":
		c.t.add(extra+"usr/lib/udev/rules.d/70-foundry-usb-readonly.rules", 0o644,
			"# USB mass storage is read-only (security.usbStorage: read-only)\n"+
				"ACTION==\"add|change\", SUBSYSTEM==\"block\", ENV{ID_BUS}==\"usb\", RUN+=\"/usr/sbin/blockdev --setro $devnode\"\n")
	case "block":
		c.t.add(extra+"usr/lib/modprobe.d/70-foundry-usb-block.conf", 0o644,
			"# USB mass storage is blocked (security.usbStorage: block)\ninstall usb_storage /bin/false\ninstall uas /bin/false\n")
	}
	if sec.Level == "hardened" {
		c.pkgs["auditd"] = true
		c.t.add(extra+"etc/audit/rules.d/50-foundry.rules", 0o640, strings.Join([]string{
			"-w /etc/sudoers -p wa -k foundry-sudoers",
			"-w /etc/sudoers.d/ -p wa -k foundry-sudoers",
			"-w /etc/passwd -p wa -k foundry-identity",
			"-w /etc/shadow -p wa -k foundry-identity",
			"-w /etc/polkit-1/ -p wa -k foundry-polkit",
			"-a always,exit -F arch=b64 -S init_module,finit_module -k foundry-modules",
			"-a always,exit -F arch=b64 -S execve -F perm=x -F euid=0 -F auid>=1000 -F auid!=unset -k foundry-root-exec",
		}, "\n")+"\n")
	}
	c.values["security"] = map[string]any{"level": sec.Level, "diskEncryption": sec.DiskEncryption, "secureBoot": sec.SecureBoot}
}

func (c *ctx) sysctl(name string, kv map[string]string) {
	keys := make([]string, 0, len(kv))
	for k := range kv {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var w strings.Builder
	w.WriteString("# Generated by Foundry\n")
	for _, k := range keys {
		fmt.Fprintf(&w, "%s = %s\n", k, kv[k])
	}
	c.t.add(extra+"usr/lib/sysctl.d/"+name, 0o644, w.String())
}

// ------------------------------------------------------------------ access

const lockedPolkit = `// Generated by Foundry: locked system — users cannot perform admin actions.
polkit.addRule(function(action, subject) {
  if (action.id.indexOf("org.freedesktop.NetworkManager.") === 0 && subject.active && subject.local) return polkit.Result.YES;
  if ((action.id == "org.freedesktop.login1.power-off" || action.id == "org.freedesktop.login1.reboot" ||
       action.id == "org.freedesktop.login1.suspend") && subject.active && subject.local) return polkit.Result.YES;
  if (subject.user == "foundry-agent") return polkit.Result.NOT_HANDLED;
  return polkit.Result.NO;
});
`

func (c *ctx) access() {
	acc := c.s.Access
	switch acc.RootModel {
	case "locked":
		c.t.add(extra+"usr/share/polkit-1/rules.d/10-foundry-locked.rules", 0o644, lockedPolkit)
		delete(c.pkgs, "sudo")
	case "admin-password":
		c.t.add(extra+"etc/sudoers.d/10-foundry", 0o440,
			"# Generated by Foundry (access.rootModel: admin-password)\nDefaults timestamp_timeout=5\nDefaults use_pty\nDefaults logfile=/var/log/sudo.log\n%sudo ALL=(ALL:ALL) ALL\n")
	case "developer":
		c.t.add(extra+"etc/sudoers.d/10-foundry", 0o440,
			"# Generated by Foundry (access.rootModel: developer)\nDefaults use_pty\n%sudo ALL=(ALL:ALL) ALL\n")
		c.t.symlink(extra+"usr/local", "../var/usrlocal")
	}
	if acc.RootModel == "locked" || acc.TTYConsole == nil || !*acc.TTYConsole {
		c.t.add(extra+"usr/lib/systemd/logind.conf.d/10-foundry.conf", 0o644, "[Login]\nNAutoVTs=0\nReserveVT=0\n")
	}
	users := []map[string]any{}
	if acc.Users != nil {
		for _, u := range acc.Users.Predefined {
			users = append(users, map[string]any{"name": u.Name, "admin": u.Admin, "passwordHash": u.PasswordHash})
		}
	}
	c.values["users"] = users
	if len(users) > 0 {
		c.post = append(c.post, postUsers)
	}
	switch acc.Users.Mode {
	case "autologin-kiosk":
		c.t.add(extra+"usr/lib/sysusers.d/foundry-kiosk.conf", 0o644,
			"u foundry-kiosk - \"Kiosk session\" /var/lib/foundry-kiosk /usr/sbin/nologin\nm foundry-kiosk video\nm foundry-kiosk render\nm foundry-kiosk input\nm foundry-kiosk audio\n")
		c.t.add(extra+"usr/lib/tmpfiles.d/foundry-kiosk.conf", 0o644, "d /var/lib/foundry-kiosk 0700 foundry-kiosk foundry-kiosk -\n")
	case "firstboot":
		switch c.s.Foundation.Profile {
		case "desktop-gnome":
			c.pkgs["gnome-initial-setup"] = true
		default:
			c.oobe()
		}
	}
}

// postUsers creates predefined users from values.json (no shell interpolation).
const postUsers = `# Predefined users (access.users.predefined)
python3 - <<'PY'
import json, subprocess
v = json.load(open("/usr/lib/foundry/values.json"))
for u in v.get("users", []):
    args = ["useradd", "--create-home", "--shell", "/bin/bash"]
    if u.get("passwordHash"):
        args += ["--password", u["passwordHash"]]
    if u.get("admin"):
        args += ["--groups", "sudo"]
    subprocess.run(args + ["--", u["name"]], check=True)
PY
`

// ------------------------------------------------------------------ kernel

func (c *ctx) kernel() {
	k := c.s.Kernel
	pre := []string{"systemd.firstboot=no"}
	if c.graphical() {
		pre = append(pre, "quiet", "splash")
	}
	if k.Flavor == "realtime" {
		pre = append(pre, "threadirqs")
	}
	c.cmdline = append(pre, c.cmdline...)
	c.cmdline = append(c.cmdline, k.ExtraCmdline...)
	c.cmdline = uniqOrdered(c.cmdline)
}

// ------------------------------------------------------------------ memory

func (c *ctx) memory() {
	prof := c.s.Memory.Profile
	if prof == "auto" {
		if c.kioskLike() {
			prof = "low-ram"
		} else if c.s.Foundation.Profile == "server" {
			prof = "workstation"
		} else {
			prof = "desktop"
		}
	}
	type mp struct{ zram, swappiness, wsf, dirty, dirtyBg string }
	m := map[string]mp{
		"low-ram":     {"min(ram, 4096)", "180", "125", "67108864", "16777216"},
		"desktop":     {"min(ram / 2, 8192)", "150", "125", "268435456", "67108864"},
		"workstation": {"min(ram / 4, 8192)", "100", "10", "", ""},
	}[prof]
	c.t.add(extra+"usr/lib/systemd/zram-generator.conf", 0o644,
		fmt.Sprintf("# Generated by Foundry (memory.profile: %s)\n[zram0]\nzram-size = %s\ncompression-algorithm = zstd\nswap-priority = 100\nfs-type = swap\n", prof, m.zram))
	sys := map[string]string{
		"vm.swappiness":             m.swappiness,
		"vm.watermark_boost_factor": "0",
		"vm.watermark_scale_factor": m.wsf,
		"vm.page-cluster":           "0",
	}
	if m.dirty != "" {
		sys["vm.dirty_bytes"] = m.dirty
		sys["vm.dirty_background_bytes"] = m.dirtyBg
	}
	c.sysctl("60-foundry-memory.conf", sys)
	c.t.add(extra+"usr/lib/tmpfiles.d/foundry-thp.conf", 0o644, "w- /sys/kernel/mm/transparent_hugepage/enabled - - - - madvise\n")
	c.t.add(extra+"usr/lib/systemd/system/user@.service.d/10-foundry-oomd.conf", 0o644,
		"[Service]\nManagedOOMMemoryPressure=kill\nManagedOOMMemoryPressureLimit=50%\n")
	c.t.add(extra+"usr/lib/systemd/system/-.slice.d/10-foundry-oomd.conf", 0o644, "[Slice]\nManagedOOMSwap=kill\n")
	c.t.add(extra+"usr/lib/systemd/oomd.conf.d/10-foundry.conf", 0o644, "[OOM]\nDefaultMemoryPressureDurationSec=20s\nSwapUsedLimit=90%\n")
	c.enable("systemd-oomd.service")
	c.values["memoryProfile"] = prof
}

// ----------------------------------------------------------------- updates

func (c *ctx) updates() {
	l := c.labels
	dir := extra + "usr/lib/sysupdate.d/"
	src := "[Source]\nType=regular-file\nPath=/var/lib/foundry/staging\n"
	part := func(name, kind, srcPattern, tgtPattern string) {
		c.t.add(dir+name, 0o644, "[Transfer]\nProtectVersion=%A\n\n"+src+
			"MatchPattern="+srcPattern+"\n\n[Target]\nType=partition\nPath=auto\nMatchPattern="+tgtPattern+
			"\nMatchPartitionType="+kind+"\nPartitionFlags=0\nReadOnly=1\n")
	}
	// @u carries the partition UUID in the file name: for usr and usr-verity it
	// is derived from the verity root hash, which is how usrhash= finds them.
	part("50-usr.transfer", "usr", l.Prefix+"_@v_@u.usr.raw", l.Prefix+"_@v")
	part("51-usr-verity.transfer", "usr-verity", l.Prefix+"_@v_@u.usr-verity.raw", l.Prefix+"_@v_v")
	part("52-usr-verity-sig.transfer", "usr-verity-sig", l.Prefix+"_@v_@u.usr-verity-sig.raw", l.Prefix+"_@v_s")
	c.t.add(dir+"60-uki.transfer", 0o644, "[Transfer]\nProtectVersion=%A\n\n"+src+
		"MatchPattern="+l.Prefix+"_@v.efi\n\n[Target]\nType=regular-file\nPath=/EFI/Linux\nPathRelativeTo=boot\n"+
		"MatchPattern="+l.Prefix+"_@v+@l-@d.efi "+l.Prefix+"_@v+@l.efi "+l.Prefix+"_@v.efi\nMode=0444\nTriesLeft=3\nTriesDone=0\nInstancesMax=2\n")
	// systemd-sysupdate writes partitions and files through systemd-import,
	// which Debian/Ubuntu ship in systemd-container.
	c.pkgs["systemd-container"] = true
	// The agent verifies TUF metadata and stages files; sysupdate's own timers stay off.
	c.disable("systemd-sysupdate.timer", "systemd-sysupdate-reboot.timer")
	c.t.add(extra+"usr/lib/tmpfiles.d/foundry-staging.conf", 0o644, "d /var/lib/foundry 0750 root root -\nd /var/lib/foundry/staging 0750 root root -\n")
	if *c.s.Security.AutoUpdates || c.s.Ecosystem.Fleet.Enroll {
		c.agent()
	}
}

func (c *ctx) agent() {
	c.t.component(extra+"usr/lib/foundry/foundry-agent", "foundry-agent", 0o755)
	p := c.in.Platform
	cfg := map[string]any{
		"tenant":      p.Tenant,
		"fleetUrl":    p.FleetURL,
		"updateUrl":   p.UpdateURL,
		"osId":        c.s.Branding.OSID,
		"labelPrefix": c.labels.Prefix,
		"enroll":      c.s.Ecosystem.Fleet.Enroll,
		"group":       c.s.Ecosystem.Fleet.Group,
		"autoUpdates": *c.s.Security.AutoUpdates,
	}
	c.t.add(extra+"usr/lib/foundry/agent.json", 0o644, mustJSON(cfg))
	c.t.add(extra+"usr/lib/systemd/system/foundry-agent.service", 0o644, `[Unit]
Description=Foundry device agent
Documentation=https://docs.foundry.dev/agent
After=network-online.target
Wants=network-online.target

[Service]
Type=notify
ExecStart=/usr/lib/foundry/foundry-agent run
Restart=always
RestartSec=10
WatchdogSec=120
StateDirectory=foundry-agent
Environment=GOMEMLIMIT=40MiB GOGC=50
MemoryMax=64M
CPUQuota=20%
NoNewPrivileges=yes
ProtectHome=yes
PrivateTmp=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictSUIDSGID=yes
LockPersonality=yes
ReadWritePaths=/var/lib/foundry /boot /efi /run

[Install]
WantedBy=multi-user.target
`)
	c.enable("foundry-agent.service")
}

