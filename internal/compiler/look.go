func gradientSVG(a, b string) string {
	return fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" width="3840" height="2160" viewBox="0 0 3840 2160">
<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient></defs>
<rect width="3840" height="2160" fill="url(#g)"/>
</svg>
`, a, b)
}

// shade darkens/lightens a hex color by factor f (−1..1).
func shade(h string, f float64) string {
	r, g, b := hexToRGB(h)
	adj := func(x int) int {
		v := float64(x)
		if f < 0 {
			v *= 1 + f
		} else {
			v += (255 - v) * f
		}
		return int(math.Round(math.Max(0, math.Min(255, v))))
	}
	return fmt.Sprintf("#%02X%02X%02X", adj(r), adj(g), adj(b))
}

// gnomeAccent maps a hex colour to the nearest GNOME ≥ 47 accent name by hue.
func gnomeAccent(h string) string {
	r, g, b := hexToRGB(h)
	rf, gf, bf := float64(r)/255, float64(g)/255, float64(b)/255
	mx, mn := math.Max(rf, math.Max(gf, bf)), math.Min(rf, math.Min(gf, bf))
	if mx-mn < 0.12 {
		return "slate"
	}
	var hue float64
	switch mx {
	case rf:
		hue = math.Mod((gf-bf)/(mx-mn), 6)
	case gf:
		hue = (bf-rf)/(mx-mn) + 2
	default:
		hue = (rf-gf)/(mx-mn) + 4
	}
	hue *= 60
	if hue < 0 {
		hue += 360
	}
	switch {
	case hue < 15 || hue >= 345:
		return "red"
	case hue < 40:
		return "orange"
	case hue < 65:
		return "yellow"
	case hue < 160:
		return "green"
	case hue < 195:
		return "teal"
	case hue < 255:
		return "blue"
	case hue < 290:
		return "purple"
	default:
		return "pink"
	}
}

func (c *ctx) wallpaperPath() string {
	l := c.s.Look
	dir := "usr/share/backgrounds/foundry/"
	if l.Wallpaper != nil && l.Wallpaper.Asset != "" {
		ext := c.in.AssetExt[l.Wallpaper.Asset]
		p := dir + "wallpaper" + ext
		c.t.asset(extra+p, l.Wallpaper.Asset)
		return "/" + p
	}
	cols, ok := [2]string{}, false
	if l.Wallpaper != nil && l.Wallpaper.Catalog != "" {
		cols, ok = catalogWallpapers[l.Wallpaper.Catalog]
	}
	if !ok {
		cols = [2]string{shade(l.Theme.Accent, -0.35), shade(l.Theme.Accent, 0.25)}
	}
	p := dir + "wallpaper.svg"
	c.t.add(extra+p, 0o644, gradientSVG(cols[0], cols[1]))
	return "/" + p
}

func (c *ctx) look() {
	if !c.graphical() {
		return
	}
	l := c.s.Look
	c.plymouth()
	if !c.desktop() {
		return
	}
	wp := c.wallpaperPath()
	font := fontFamilies[l.Theme.Font]
	if font == "" {
		font = "Cantarell"
	}
	switch c.s.Foundation.Profile {
	case "desktop-gnome":
		c.gnome(wp, font)
	case "desktop-kde":
		c.kde(wp, font)
	}
}

func (c *ctx) gnome(wp, font string) {
	l, locked := c.s.Look, c.s.Access.RootModel == "locked"
	var w strings.Builder
	w.WriteString("# Generated by Foundry\n[org/gnome/desktop/interface]\n")
	scheme := map[string]string{"dark": "prefer-dark", "light": "prefer-light", "auto": "default"}[l.Theme.Mode]
	fmt.Fprintf(&w, "color-scheme='%s'\nfont-name='%s 11'\n", scheme, font)
	if it := iconThemes[l.Theme.IconTheme]; it != "" {
		fmt.Fprintf(&w, "icon-theme='%s'\n", it)
	}
	if c.base.GNOMEAccent {
		fmt.Fprintf(&w, "accent-color='%s'\n", gnomeAccent(l.Theme.Accent))
	} else {
		c.warn = append(c.warn, "This GNOME version has no accent colours; the accent is applied to the wallpaper only.")
	}
	fmt.Fprintf(&w, "\n[org/gnome/desktop/background]\npicture-uri='file://%s'\npicture-uri-dark='file://%s'\npicture-options='zoom'\n", wp, wp)
	fmt.Fprintf(&w, "\n[org/gnome/desktop/screensaver]\npicture-uri='file://%s'\n", wp)
	preset := l.Layout.Preset
	var exts []string
	dock := map[string]string{"dock-bottom": "BOTTOM", "dock-left": "LEFT", "taskbar-bottom": "BOTTOM"}[preset]
	extend, fixed, icon := preset == "taskbar-bottom", true, 0
	var favorites []string
	if doc := c.customLayout(); doc != nil {
		dock = ""
		for _, p := range doc.Panels {
			if p.Edge == "top" {
				continue // GNOME's top bar is fixed
			}
			dock, extend, fixed, icon = strings.ToUpper(p.Edge), p.Style == "bar", !p.Autohide, min(64, max(16, p.Size*3/4))
			break
		}
		favorites = doc.Favorites
		if len(doc.Panels) > 1 {
			c.warn = append(c.warn, "GNOME shows one dock plus its fixed top bar; extra panels of the custom layout are ignored.")
		}
	}
	if dock != "" && strings.HasPrefix(c.base.ID, "ubuntu") {
		c.pkgs["gnome-shell-extension-ubuntu-dock"] = true
		exts = append(exts, "'ubuntu-dock@ubuntu.com'")
		fmt.Fprintf(&w, "\n[org/gnome/shell/extensions/dash-to-dock]\ndock-position='%s'\nextend-height=%v\ndock-fixed=%v\n", dock, extend, fixed)
		if icon > 0 {
			fmt.Fprintf(&w, "dash-max-icon-size=%d\n", icon)
		}
	}
	if len(favorites) > 0 {
		q := make([]string, len(favorites))
		for i, f := range favorites {
			q[i] = "'" + f + "'" // validated: [A-Za-z0-9._-]+.desktop
		}
		fmt.Fprintf(&w, "\n[org/gnome/shell]\nfavorite-apps=[%s]\n", strings.Join(q, ", "))
	}
	if c.s.Ecosystem.Handoff.Enabled {
		exts = append(exts, "'gsconnect@andyholmes.github.io'")
	}
	if len(exts) > 0 {
		if len(favorites) == 0 {
			w.WriteString("\n[org/gnome/shell]\n")
		}
		fmt.Fprintf(&w, "enabled-extensions=[%s]\n", strings.Join(exts, ", "))
	}
	c.t.add(extra+"etc/dconf/profile/user", 0o644, "user-db:user\nsystem-db:local\n")
	c.t.add(extra+"etc/dconf/db/local.d/10-foundry", 0o644, w.String())
	if locked {
		c.t.add(extra+"etc/dconf/db/local.d/locks/10-foundry", 0o644,
			"/org/gnome/desktop/background/picture-uri\n/org/gnome/desktop/background/picture-uri-dark\n/org/gnome/desktop/interface/color-scheme\n/org/gnome/desktop/lockdown/disable-command-line\n")
		c.t.add(extra+"etc/dconf/db/local.d/20-foundry-lockdown", 0o644, "[org/gnome/desktop/lockdown]\ndisable-command-line=true\n")
	}
	if l.LoginScreen != nil && l.LoginScreen.Background != "" {
		c.warn = append(c.warn, "Custom login-screen backgrounds are not supported on GNOME yet; the default is used.")
	}
	c.post = append(c.post, "# Compile dconf defaults\ndconf update\n")
}

func (c *ctx) kde(wp, font string) {
	l := c.s.Look
	r, g, b := hexToRGB(l.Theme.Accent)
	laf := "org.kde.breeze.desktop"
	if l.Theme.Mode == "dark" {
		laf = "org.kde.breezedark.desktop"
	}
	icons := iconThemes[l.Theme.IconTheme]
	if icons == "" {
		icons = "breeze"
	}
	c.t.add(extra+"etc/xdg/kdeglobals", 0o644, fmt.Sprintf(
		"# Generated by Foundry\n[General]\nAccentColor=%d,%d,%d\nfont=%s,10,-1,5,50,0,0,0,0,0\n\n[Icons]\nTheme=%s\n\n[KDE]\nLookAndFeelPackage=%s\n", r, g, b, font, icons, laf))
	loc := map[string]string{"dock-bottom": "bottom", "dock-left": "left", "taskbar-bottom": "bottom", "minimal": "top"}[l.Layout.Preset]
	js := fmt.Sprintf(`// Generated by Foundry: first-start defaults for every user.
var wp = "file://%s";
desktops().forEach(function (d) {
  d.wallpaperPlugin = "org.kde.image";
  d.currentConfigGroup = ["Wallpaper", "org.kde.image", "General"];
  d.writeConfig("Image", wp);
});
`, wp)
	if doc := c.customLayout(); doc != nil {
		js += kdeLayoutJS(doc)
	} else {
		if loc != "" {
			js += fmt.Sprintf("panels().forEach(function (p) { p.location = %q; });\n", loc)
		}
		if l.Layout.Preset == "dock-bottom" || l.Layout.Preset == "dock-left" {
			js += "panels().forEach(function (p) { p.alignment = \"center\"; p.lengthMode = \"fit\"; p.hiding = \"dodgewindows\"; });\n"
		}
	}
	c.t.add(extra+"usr/share/plasma/shells/org.kde.plasma.desktop/contents/updates/foundry-defaults.js", 0o644, js)
	bg := wp
	if l.LoginScreen != nil && l.LoginScreen.Background != "" {
		p := "usr/share/backgrounds/foundry/login" + c.in.AssetExt[l.LoginScreen.Background]
		c.t.asset(extra+p, l.LoginScreen.Background)
		bg = "/" + p
	}
	c.t.add(extra+"usr/share/sddm/themes/breeze/theme.conf.user", 0o644, "[General]\nbackground="+bg+"\n")
	c.t.add(extra+"etc/sddm.conf.d/10-foundry.conf", 0o644, "[Theme]\nCurrent=breeze\n")
}

func plymouthText(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r >= 0x20 && r != '"' && r != '\\' && r != 0x7f {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func (c *ctx) plymouth() {
	bs := c.s.Look.BootSplash
	r, g, b := hexToRGB(bs.Background)
	dir := "usr/share/plymouth/themes/foundry/"
	c.t.add(extra+dir+"foundry.plymouth", 0o644, "[Plymouth Theme]\nName=Foundry\nDescription=Generated boot splash\nModuleName=script\n\n[script]\nImageDir=/"+dir[:len(dir)-1]+"\nScriptFile=/"+dir+"foundry.script\n")
	var sc strings.Builder
	fmt.Fprintf(&sc, "Window.SetBackgroundTopColor(%.3f, %.3f, %.3f);\nWindow.SetBackgroundBottomColor(%.3f, %.3f, %.3f);\n",
		float64(r)/255, float64(g)/255, float64(b)/255, float64(r)/255, float64(g)/255, float64(b)/255)
	if bs.Logo != "" && c.in.AssetExt[bs.Logo] == ".png" {
		c.t.asset(extra+dir+"logo.png", bs.Logo)
		sc.WriteString("logo = Image(\"logo.png\");\n")
	} else {
		if bs.Logo != "" {
			c.warn = append(c.warn, "Boot logo must be a PNG; showing the OS name instead.")
		}
		fmt.Fprintf(&sc, "logo = Image.Text(\"%s\", 1, 1, 1, 1, \"Sans 28\");\n", plymouthText(c.s.Branding.OSName))
	}
	sc.WriteString("s = Sprite(logo);\ns.SetX(Window.GetWidth() / 2 - logo.GetWidth() / 2);\ns.SetY(Window.GetHeight() / 2 - logo.GetHeight() / 2);\n")
	c.t.add(extra+dir+"foundry.script", 0o644, sc.String())
	c.post = append(c.post, `# Boot splash theme
update-alternatives --install /usr/share/plymouth/themes/default.plymouth default.plymouth /usr/share/plymouth/themes/foundry/foundry.plymouth 200
update-alternatives --set default.plymouth /usr/share/plymouth/themes/foundry/foundry.plymouth
`)
}

// customLayout returns the validated custom layout, if the spec uses one.
func (c *ctx) customLayout() *osspec.LayoutDoc {
	d := c.s.Look.Layout.Custom
	if d == "" {
		return nil
	}
	if doc := c.in.Layouts[d]; doc != nil {
		return doc
	}
	c.warn = append(c.warn, "The custom layout document was not supplied; the default layout is used.")
	return nil
}

var kdeApplets = map[string]string{
	"launcher": "org.kde.plasma.kickoff", "tasks": "org.kde.plasma.icontasks", "favorites": "org.kde.plasma.icontasks",
	"tray": "org.kde.plasma.systemtray", "clock": "org.kde.plasma.digitalclock", "search": "org.kde.milou",
	"spacer": "org.kde.plasma.panelspacer", "desktops": "org.kde.plasma.pager", "trash": "org.kde.plasma.trash",
}

// kdeLayoutJS recreates the panels of a custom layout. Every value comes
// from the validated document (enums, bounded ints, desktop-id regex).
func kdeLayoutJS(doc *osspec.LayoutDoc) string {
	var b strings.Builder
	b.WriteString("panels().forEach(function (p) { p.remove(); });\n")
	var launchers []string
	for _, f := range doc.Favorites {
		launchers = append(launchers, fmt.Sprintf("%q", "applications:"+f))
	}
	for i, p := range doc.Panels {
		fmt.Fprintf(&b, "var p%d = new Panel(\"org.kde.panel\");\np%d.location = %q;\np%d.height = %d;\n", i, i, p.Edge, i, p.Size)
		if p.Autohide {
			fmt.Fprintf(&b, "p%d.hiding = \"autohide\";\n", i)
		}
		if p.Style == "dock" {
			fmt.Fprintf(&b, "p%d.alignment = \"center\";\np%d.lengthMode = \"fit\";\n", i, i)
		}
		tasks := false
		for _, it := range p.Items {
			a := kdeApplets[it]
			if a == "org.kde.plasma.icontasks" {
				if tasks {
					continue
				}
				tasks = true
				fmt.Fprintf(&b, "var t%d = p%d.addWidget(%q);\nt%d.currentConfigGroup = [\"General\"];\nt%d.writeConfig(\"launchers\", [%s]);\n", i, i, a, i, i, strings.Join(launchers, ", "))
				continue
			}
			fmt.Fprintf(&b, "p%d.addWidget(%q);\n", i, a)
		}
	}
	return b.String()
}
