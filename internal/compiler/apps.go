package compiler

import (
	"fmt"
	"net/url"
	"sort"
	"strings"
)

const flatpakInstaller = `#!/usr/bin/python3
"""Install the OS's preinstalled Flatpak apps (first boot, retried until done).

Prefers the offline sideload repository baked into the image; falls back to
the configured remote when online. Marks completion per app list digest.
"""
import hashlib, json, os, subprocess, sys
cfg = json.load(open("/usr/lib/foundry/flatpaks.json"))
refs = cfg.get("refs", [])
digest = hashlib.sha256(json.dumps(refs).encode()).hexdigest()[:16]
mark = f"/var/lib/foundry/flatpaks-{digest}.done"
if not refs or os.path.exists(mark):
    sys.exit(0)
remote = cfg.get("remote", "foundry")
sideload = "/usr/share/foundry/flatpak-sideload"
failed = []
for ref in refs:
    args = ["flatpak", "install", "--system", "--noninteractive", "--or-update"]
    if os.path.isdir(sideload):
        args.append("--sideload-repo=" + sideload)
    if subprocess.run(args + [remote, ref]).returncode != 0:
        failed.append(ref)
if failed:
    print("foundry-flatpak: will retry:", " ".join(failed), file=sys.stderr)
    sys.exit(1)
os.makedirs("/var/lib/foundry", exist_ok=True)
open(mark, "w").close()
`

func (c *ctx) apps() {
	var refs []string
	for _, a := range c.s.Apps.Preinstalled {
		if strings.HasPrefix(a, "flatpak:") {
			refs = append(refs, strings.TrimPrefix(a, "flatpak:"))
		}
	}
	sort.Strings(refs)
	if len(refs) == 0 && !c.s.Ecosystem.AppStore.Enabled {
		return
	}
	c.pkgs["flatpak"] = true
	c.t.add(extra+"usr/lib/foundry/flatpaks.json", 0o644, mustJSON(map[string]any{"remote": "foundry", "refs": refs}))
	if c.in.Platform.FlatpakRemote != "" {
		c.t.add(extra+"etc/flatpak/remotes.d/foundry.flatpakrepo", 0o644, c.in.Platform.FlatpakRemote)
	} else {
		c.warn = append(c.warn, "No app repository is configured for this platform; preinstalled apps install once fleet policy provides one.")
	}
	if len(refs) == 0 {
		return
	}
	c.t.add(extra+"usr/lib/foundry/flatpak-install", 0o755, flatpakInstaller)
	c.t.add(extra+"usr/lib/systemd/system/foundry-flatpak-install.service", 0o644, `[Unit]
Description=Install preinstalled apps
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/usr/lib/foundry/flatpak-install
Restart=on-failure
RestartSec=5min
Nice=10
IOSchedulingClass=idle

[Install]
WantedBy=multi-user.target
`)
	c.enable("foundry-flatpak-install.service")
}

func (c *ctx) ecosystem() {
	e := c.s.Ecosystem
	switch c.s.Foundation.Profile {
	case "kiosk-cage":
		c.kiosk("/usr/bin/cage -s -- /usr/lib/foundry/foundry-kiosk-browser", "70%", "85%")
		c.t.add(extra+"usr/lib/foundry/foundry-kiosk-browser", 0o755, embedded("kiosk/foundry-kiosk-browser"))
		k := e.Kiosk
		c.t.add(extra+"usr/lib/foundry/kiosk.json", 0o644, mustJSON(map[string]any{
			"url": k.URL, "allowedDomains": nonNil(k.AllowedDomains), "idleResetMinutes": k.IdleResetMinutes}))
	case "thin-client":
		host := ""
		if e.Kiosk != nil {
			if u, err := url.Parse(e.Kiosk.URL); err == nil {
				host = u.Hostname()
			}
		}
		c.kiosk("/usr/bin/cage -s -- /usr/bin/wlfreerdp /f +auto-reconnect /cert:tofu /v:"+host, "80%", "90%")
	}
	if c.graphical() {
		c.post = append(c.post, "systemctl set-default graphical.target\n")
	} else {
		c.post = append(c.post, "systemctl set-default multi-user.target\n")
	}

	id := e.Identity
	c.values["identity"] = map[string]any{"provider": id.Provider, "issuer": id.Issuer, "clientId": id.ClientID, "domain": id.Domain}
	switch id.Provider {
	case "oidc":
		c.t.add(extra+"usr/lib/foundry/identity.json", 0o644, mustJSON(map[string]any{"provider": "oidc", "issuer": id.Issuer, "clientId": id.ClientID}))
		c.t.component(extra+"usr/lib/foundry/foundry-oidc-login", "foundry-oidc-login", 0o755)
	case "ldap", "ad":
		var w strings.Builder
		fmt.Fprintf(&w, "# Generated by Foundry. Completed at enrollment (realm join / bind credentials).\n[sssd]\nservices = nss, pam\ndomains = %s\n\n[domain/%s]\n", id.Domain, id.Domain)
		if id.Provider == "ad" {
			w.WriteString("id_provider = ad\naccess_provider = ad\n")
		} else {
			fmt.Fprintf(&w, "id_provider = ldap\nauth_provider = ldap\nldap_uri = ldaps://%s\n", id.Domain)
		}
		w.WriteString("cache_credentials = true\nfallback_homedir = /home/%u\ndefault_shell = /bin/bash\n")
		c.t.add(extra+"etc/sssd/sssd.conf", 0o600, w.String())
		c.post = append(c.post, "pam-auth-update --enable mkhomedir || true\n")
	}

	if e.Sync.Provider != "none" {
		server := e.Sync.URL
		if e.Sync.Provider == "hosted" {
			server = c.in.Platform.SyncURL
		}
		c.t.add(extra+"usr/lib/foundry/sync.json", 0o644, mustJSON(map[string]any{"provider": e.Sync.Provider, "server": server}))
		c.t.add(extra+"etc/xdg/autostart/foundry-sync.desktop", 0o644,
			"[Desktop Entry]\nType=Application\nName=File sync\nExec=nextcloud --background\nX-GNOME-Autostart-enabled=true\nNoDisplay=true\n")
	}
}

func (c *ctx) kiosk(exec, high, max string) {
	c.t.add(extra+"usr/lib/systemd/system/foundry-kiosk.service", 0o644, fmt.Sprintf(`[Unit]
Description=Foundry kiosk session
After=systemd-user-sessions.service plymouth-quit-wait.service systemd-logind.service
Conflicts=getty@tty1.service
OnFailure=

[Service]
User=foundry-kiosk
PAMName=login
TTYPath=/dev/tty1
TTYReset=yes
TTYVHangup=yes
TTYVTDisallocate=yes
UtmpIdentifier=tty1
UtmpMode=user
StandardInput=tty-fail
Environment=XDG_SESSION_TYPE=wayland
ExecStart=%s
Restart=always
RestartSec=2
MemoryHigh=%s
MemoryMax=%s
ManagedOOMPreference=avoid

[Install]
WantedBy=graphical.target
`, exec, high, max))
	c.enable("foundry-kiosk.service")
	c.disable("getty@.service")
}

// oobe adds the first-boot account creation app (desktops without a vendor OOBE).
func (c *ctx) oobe() {
	if !c.graphical() {
		return
	}
	c.pkgs["cage"] = true
	c.pkgs["python3-gi"] = true
	c.pkgs["gir1.2-webkit2-4.1"] = true
	c.pkgs["gir1.2-gtk-3.0"] = true
	c.values["rootModel"] = c.s.Access.RootModel
	c.t.add(extra+"usr/lib/foundry/foundry-oobe", 0o755, embedded("oobe/foundry-oobe"))
	c.t.add(extra+"usr/lib/systemd/system/foundry-oobe.service", 0o644, `[Unit]
Description=Foundry first-boot setup
ConditionPathExists=!/var/lib/foundry/oobe-done
Before=display-manager.service
After=systemd-user-sessions.service plymouth-quit-wait.service systemd-logind.service
Conflicts=getty@tty1.service

[Service]
Type=oneshot
PAMName=login
TTYPath=/dev/tty1
TTYReset=yes
TTYVHangup=yes
StandardInput=tty-fail
TimeoutStartSec=infinity
ExecStart=/usr/bin/cage -s -- /usr/lib/foundry/foundry-oobe

[Install]
WantedBy=graphical.target
`)
	c.enable("foundry-oobe.service")
}

func nonNil(xs []string) []string {
	if xs == nil {
		return []string{}
	}
	return xs
}
